def get_mac_vendor(mac: str) -> str:
    if not mac:
        return ""
    mac = mac.lower().replace("-", ":")
    if len(mac) < 8:
        return ""
    oui = mac[:8]
    vendor = MAC_OUI_VENDORS.get(oui, "")
    return vendor


def get_device_category(vendor: str) -> str:
    if not vendor:
        return ""
    v = vendor.lower()
    network_vendors = ["tp-link", "mercury", "fast", "huawei", "h3c", "ruijie", "maipu",
                       "cisco", "asus", "netgear", "tenda", "ubiquiti", "xiaomi"]
    phone_vendors = ["apple", "huawei", "xiaomi", "honor", "oppo", "vivo", "samsung", "oneplus"]
    printer_vendors = ["hp", "hewlett", "canon", "epson", "brother", "xerox", "lexmark", "ricoh"]
    server_vendors = ["dell", "hp", "hewlett", "lenovo", "inspur", "huawei", "supermicro"]
    pc_vendors = ["lenovo", "dell", "hp", "hewlett", "asus", "acer", "msi", "gigabyte"]

    if any(nw in v for nw in network_vendors):
        return "网络设备"
    if any(pv in v for pv in phone_vendors):
        return "手机/移动设备"
    if any(pv in v for pv in printer_vendors):
        return "打印机/办公设备"
    if any(sv in v for sv in server_vendors):
        return "服务器"
    if any(pc in v for pc in pc_vendors):
        return "电脑/笔记本"
    if "vmware" in v or "virtual" in v:
        return "虚拟机"
    return "其他"


def load_oui_from_file(filepath: str) -> int:
    if not os.path.exists(filepath):
        return 0
    try:
        with open(filepath, 'r', encoding='utf-8') as f:
            data = json.load(f)
        count = 0
        for oui, vendor in data.items():
            oui_lower = oui.lower().replace("-", ":")
            if oui_lower not in MAC_OUI_VENDORS:
                MAC_OUI_VENDORS[oui_lower] = vendor
                count += 1
        return count
    except Exception:
        return 0
